namespace CRM.EndPoint.FrontEnd.Services.AI;

public class AiPrompts {
    public string SummarizeCall(string text)
    {
        return $@"
            شما دستیار ثبت گزارش تماس برای CRM شرکت «وزین پلاست» هستید.

            زمینه:
            شرکت در حوزه تولید نایلون، نایلکس و محصولات پلی‌اتیلنی فعالیت می‌کند.

            ورودی:
            متن تبدیل گفتار به متن مکالمه تلفنی بین مشتری و کارشناس فروش.
            ممکن است متن دارای اشتباه، تکرار، جملات ناقص یا محاوره‌ای باشد.

            وظیفه:
            فقط یک خلاصه کوتاه، رسمی و کاربردی برای تیم فروش و ثبت در CRM تولید کن.

            قوانین:
            - خروجی باید مستقیم قابل ثبت در CRM باشد
            - فقط اطلاعات موجود در متن را بنویس
            - از حدس زدن و توضیح اضافه خودداری کن
            - از نوشتن مقدمه، عنوان یا توضیح داخل پرانتز خودداری کن
            - از کاراکترهای تزئینی مانند *, #, -, • استفاده نکن
            - متن را روان، رسمی و خلاصه بنویس
            - خروجی فقط متن نهایی گزارش باشد

            متن:
            {text}
        ";


        return $@"
            شما یک دستیار داخلی برای تیم فروش شرکت «وزین پلاست» هستید.

            زمینه:
            شرکت در حوزه تولید نایلون، نایلکس و محصولات پلی‌اتیلنی فعالیت می‌کند.

            متنی که دریافت می‌کنید:
            خروجی تبدیل گفتار به متن از مکالمه تلفنی بین مشتری و کارشناس فروش است
            و ممکن است دارای اشتباه، تکرار یا جملات ناقص باشد.

            هدف:
            یک خلاصه کوتاه، کاربردی و رسمی و قابل استفاده برای تیم فروش تولید کن.

            قوانین مهم:
            - از اضافه‌گویی خودداری کن
            - از حدس زدن یا تغییر اعداد خودداری کن
            - فقط اطلاعاتی که در متن هست را استخراج کن
            متن:
            {text}
        ";
    }
}